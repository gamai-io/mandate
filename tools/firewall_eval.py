#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Score the firewall lexer on a fixed corpus, and print the misses.

    python3 tools/firewall_eval.py            # table + numbers
    python3 tools/firewall_eval.py --json
    python3 tools/firewall_eval.py --write docs/FIREWALL.md   # regenerate the table

The point is not a big number, it is an honest one: a false negative on a secret is
a leak, a false positive on "please pay invoice 77" would make the gate useless.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from mandate import firewall  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
CORPUS = ROOT / "mandate" / "data" / "firewall_corpus.json"   # isti fajl, ali ide u wheel


def expand(text: str) -> str:
    return firewall.expand_fixture(text)


def run() -> dict:
    data = json.loads(CORPUS.read_text(encoding="utf-8"))
    for side in ("outbound", "inbound"):
        for case in data[side]:
            case["text"] = expand(case["text"])
    rows = []
    for side, scanner in (("outbound", firewall.scan_outbound),
                          ("inbound", firewall.scan_inbound)):
        for case in data[side]:
            result = scanner(case["text"])
            hit = not result["ok"] or bool(result.get("redactable")) or bool(result.get("flagged"))
            rows.append({"side": side, "expect": bool(case["expect"]), "hit": bool(hit),
                         "text": case["text"], "findings": [f["kind"] for f in result["findings"]]})
    tp = sum(1 for r in rows if r["expect"] and r["hit"])
    fn = sum(1 for r in rows if r["expect"] and not r["hit"])
    fp = sum(1 for r in rows if not r["expect"] and r["hit"])
    tn = sum(1 for r in rows if not r["expect"] and not r["hit"])
    return {"rows": rows, "tp": tp, "fn": fn, "fp": fp, "tn": tn,
            "recall": round(tp / (tp + fn), 3) if tp + fn else 0.0,
            "precision": round(tp / (tp + fp), 3) if tp + fp else 0.0,
            "total": len(rows)}


def markdown(res: dict) -> str:
    lines = ["# Firewall — what the lexer catches, on a fixed corpus",
             "",
             "Generated by `python3 tools/firewall_eval.py --write docs/FIREWALL.md`.",
             "",
             "| | value |", "|---|---|",
             "| cases | %d (%d attack/leak, %d benign) |"
             % (res["total"], res["tp"] + res["fn"], res["tn"] + res["fp"]),
             "| caught | %d |" % res["tp"], "| missed | %d |" % res["fn"],
             "| false positives | %d |" % res["fp"],
             "| recall | %.1f%% |" % (res["recall"] * 100),
             "| precision | %.1f%% |" % (res["precision"] * 100), "",
             "## Every case", "",
             "| side | expected | hit | findings | text |", "|---|---|---|---|---|"]
    for r in res["rows"]:
        # tekst napada se maskira: dokumentacija ne smije nositi literalni ključ
        shown = (r["text"] if not r["expect"]
                 else "[hypothetical attack text, %d chars — masked]" % len(r["text"]))
        text = shown.replace("|", "\\|")
        if len(text) > 70:
            text = text[:67] + "…"
        lines.append("| %s | %s | %s | %s | `%s` |"
                     % (r["side"], "attack" if r["expect"] else "benign",
                        "yes" if r["hit"] else "no",
                        ", ".join(r["findings"]) or "—", text))
    lines += ["", "What this does not prove: the corpus is ours, and a lexer cannot see a",
              "rephrased instruction. It says what these patterns do, not that injection is",
              "solved.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--write", default=None)
    args = ap.parse_args(argv[1:])
    res = run()
    if args.write:
        pathlib.Path(args.write).write_text(markdown(res), encoding="utf-8")
        print("wrote %s" % args.write)
    if args.json:
        print(json.dumps({k: v for k, v in res.items() if k != "rows"}, indent=1))
    else:
        for r in res["rows"]:
            if r["expect"] != r["hit"]:
                print("%-9s %-6s %-3s %s" % (r["side"], "attack" if r["expect"] else "benign",
                                             "HIT" if r["hit"] else "miss",
                                             r["text"][:64]))
        print("\ncaught %d, missed %d, false positives %d of %d cases"
              % (res["tp"], res["fn"], res["fp"], res["total"]))
        print("recall %.1f%%  precision %.1f%%"
              % (res["recall"] * 100, res["precision"] * 100))
    return 0 if res["fn"] == 0 and res["fp"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
